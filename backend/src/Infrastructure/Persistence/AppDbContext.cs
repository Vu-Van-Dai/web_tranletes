using ComicPlatform.Application.Abstractions;
using ComicPlatform.Domain.Analytics;
using ComicPlatform.Domain.Auditing;
using ComicPlatform.Domain.Catalog;
using ComicPlatform.Domain.Identity;
using ComicPlatform.Domain.Library;
using ComicPlatform.Domain.Publishing;
using ComicPlatform.Domain.Settings;
using ComicPlatform.Domain.Tenancy;
using Microsoft.EntityFrameworkCore;

namespace ComicPlatform.Infrastructure.Persistence;

public sealed class AppDbContext : DbContext, IAppDbContext
{
    private readonly ITenantContext _tenant;

    public AppDbContext(DbContextOptions<AppDbContext> options, ITenantContext tenant)
        : base(options)
    {
        _tenant = tenant;
    }

    /// <summary>
    /// House id used by the fail-closed "Tenant" query filter. When no house context was resolved
    /// for this scope it is <see cref="Guid.Empty"/>, which matches no rows.
    /// </summary>
    private Guid CurrentHouseId => _tenant.IsResolved ? _tenant.HouseId : Guid.Empty;

    public DbSet<User> Users => Set<User>();
    public DbSet<RefreshToken> RefreshTokens => Set<RefreshToken>();
    public DbSet<TranslationHouse> TranslationHouses => Set<TranslationHouse>();
    public DbSet<TranslationHouseMember> TranslationHouseMembers => Set<TranslationHouseMember>();
    public DbSet<Comic> Comics => Set<Comic>();
    public DbSet<Tag> Tags => Set<Tag>();
    public DbSet<ComicTag> ComicTags => Set<ComicTag>();
    public DbSet<Chapter> Chapters => Set<Chapter>();
    public DbSet<ChapterPackage> ChapterPackages => Set<ChapterPackage>();
    public DbSet<ChapterPage> ChapterPages => Set<ChapterPage>();
    public DbSet<ProcessingJob> ProcessingJobs => Set<ProcessingJob>();
    public DbSet<StorageTask> StorageTasks => Set<StorageTask>();
    public DbSet<AuditLog> AuditLogs => Set<AuditLog>();
    public DbSet<SystemSetting> SystemSettings => Set<SystemSetting>();
    public DbSet<Follow> Follows => Set<Follow>();
    public DbSet<ReadingProgress> ReadingProgress => Set<ReadingProgress>();
    public DbSet<ComicViewDaily> ComicViewDaily => Set<ComicViewDaily>();
    public DbSet<ChapterViewDaily> ChapterViewDaily => Set<ChapterViewDaily>();
    public DbSet<ViewReceipt> ViewReceipts => Set<ViewReceipt>();
    public DbSet<ViewRejectionDaily> ViewRejectionDaily => Set<ViewRejectionDaily>();

    protected override void ConfigureConventions(ModelConfigurationBuilder configurationBuilder)
    {
        // Enums are stored as readable text; permission flags stay integers.
        configurationBuilder.Properties<SystemRole>().HaveConversion<string>().HaveMaxLength(32);
        configurationBuilder.Properties<UserStatus>().HaveConversion<string>().HaveMaxLength(32);
        configurationBuilder.Properties<HouseStatus>().HaveConversion<string>().HaveMaxLength(32);
        configurationBuilder.Properties<HouseRole>().HaveConversion<string>().HaveMaxLength(32);
        configurationBuilder.Properties<MemberStatus>().HaveConversion<string>().HaveMaxLength(32);
        configurationBuilder.Properties<ComicStatus>().HaveConversion<string>().HaveMaxLength(32);
        configurationBuilder.Properties<ChapterStatus>().HaveConversion<string>().HaveMaxLength(32);
        configurationBuilder.Properties<PackageStatus>().HaveConversion<string>().HaveMaxLength(32);
        configurationBuilder.Properties<JobStatus>().HaveConversion<string>().HaveMaxLength(32);
        configurationBuilder.Properties<JobStage>().HaveConversion<string>().HaveMaxLength(32);
        configurationBuilder.Properties<StorageTaskKind>().HaveConversion<string>().HaveMaxLength(32);
        configurationBuilder.Properties<HousePermissions>().HaveConversion<int>();
    }

    protected override void OnModelCreating(ModelBuilder b)
    {
        b.HasPostgresExtension("pg_trgm");

        ConfigureIdentity(b);
        ConfigureTenancy(b);
        ConfigureCatalog(b);
        ConfigurePublishing(b);
        ConfigureMisc(b);
        ConfigureAnalytics(b);

        // Ids are UUIDv7 generated by the domain. Telling EF they are never store-generated makes
        // entities reachable through navigations (e.g. new pages of a package) inserts, not updates.
        foreach (var entity in b.Model.GetEntityTypes())
        {
            foreach (var key in entity.FindPrimaryKey()?.Properties ?? [])
            {
                if (key.ClrType == typeof(Guid))
                {
                    key.ValueGenerated = Microsoft.EntityFrameworkCore.Metadata.ValueGenerated.Never;
                }
            }
        }
    }

    private void ConfigureAnalytics(ModelBuilder b)
    {
        // Payout ledger: no foreign keys on purpose, so history survives chapter/comic deletion.
        b.Entity<ChapterViewDaily>(e =>
        {
            e.ToTable("chapter_view_daily");
            e.HasKey(x => new { x.ChapterId, x.Day });
            e.Property(x => x.Revenue).HasPrecision(18, 4);
            e.HasIndex(x => new { x.TranslationHouseId, x.Day });
            e.HasIndex(x => new { x.ComicId, x.Day });
            e.HasIndex(x => x.Day);
            e.HasQueryFilter(QueryFilters.Tenant, x => x.TranslationHouseId == CurrentHouseId);
        });

        b.Entity<ViewReceipt>(e =>
        {
            e.ToTable("view_receipts");
            e.HasKey(x => new { x.ChapterId, x.Day, x.VisitorHash });
            e.Property(x => x.VisitorHash).HasMaxLength(64);
            e.HasIndex(x => x.Day);
        });

        b.Entity<ViewRejectionDaily>(e =>
        {
            e.ToTable("view_rejection_daily");
            e.HasKey(x => new { x.Day, x.Reason });
            e.Property(x => x.Reason).HasMaxLength(32);
        });
    }

    private static void ConfigureIdentity(ModelBuilder b)
    {
        b.Entity<User>(e =>
        {
            e.ToTable("users");
            e.HasKey(x => x.Id);
            e.Property(x => x.Username).HasMaxLength(32).IsRequired();
            e.Property(x => x.NormalizedUsername).HasMaxLength(32).IsRequired();
            e.Property(x => x.Email).HasMaxLength(320).IsRequired();
            e.Property(x => x.NormalizedEmail).HasMaxLength(320).IsRequired();
            e.Property(x => x.DisplayName).HasMaxLength(64).IsRequired();
            e.Property(x => x.PasswordHash).HasMaxLength(256).IsRequired();
            e.Property(x => x.Version).IsRowVersion();
            e.HasIndex(x => x.NormalizedUsername).IsUnique();
            e.HasIndex(x => x.NormalizedEmail).IsUnique();
            e.Ignore(x => x.IsActive);
        });

        b.Entity<RefreshToken>(e =>
        {
            e.ToTable("refresh_tokens");
            e.HasKey(x => x.Id);
            e.Property(x => x.TokenHash).HasMaxLength(64).IsRequired();
            e.Property(x => x.RevokeReason).HasMaxLength(64);
            e.HasIndex(x => x.TokenHash).IsUnique();
            e.HasIndex(x => x.UserId);
            e.HasIndex(x => x.FamilyId);
            e.HasOne<User>().WithMany().HasForeignKey(x => x.UserId).OnDelete(DeleteBehavior.Cascade);
            e.Ignore(x => x.IsRevoked);
        });
    }

    private static void ConfigureTenancy(ModelBuilder b)
    {
        b.Entity<TranslationHouse>(e =>
        {
            e.ToTable("translation_houses");
            e.HasKey(x => x.Id);
            e.Property(x => x.Name).HasMaxLength(100).IsRequired();
            e.Property(x => x.Slug).HasMaxLength(100).IsRequired();
            e.Property(x => x.Description).HasMaxLength(2000);
            e.Property(x => x.LogoKey).HasMaxLength(200);
            e.Property(x => x.CoverKey).HasMaxLength(200);
            e.Property(x => x.Tagline).HasMaxLength(TranslationHouse.TaglineMaxLength);
            e.Property(x => x.ContactEmail).HasMaxLength(254);
            e.Property(x => x.RecruitmentInfo).HasMaxLength(TranslationHouse.RecruitmentInfoMaxLength);
            e.Property(x => x.SuspendedReason).HasMaxLength(500);
            e.Property(x => x.Version).IsRowVersion();
            e.OwnsOne(x => x.Links, l => l.ToJson());
            e.HasIndex(x => x.Slug).IsUnique();
            e.HasIndex(x => x.Name).IsUnique();
            e.Ignore(x => x.IsActive);
        });

        b.Entity<TranslationHouseMember>(e =>
        {
            e.ToTable("translation_house_members");
            e.HasKey(x => x.Id);
            e.Property(x => x.Version).IsRowVersion();
            e.HasIndex(x => new { x.TranslationHouseId, x.UserId }).IsUnique();
            e.HasIndex(x => x.UserId);
            e.HasOne(x => x.TranslationHouse).WithMany().HasForeignKey(x => x.TranslationHouseId).OnDelete(DeleteBehavior.Cascade);
            e.HasOne(x => x.User).WithMany().HasForeignKey(x => x.UserId).OnDelete(DeleteBehavior.Cascade);
            e.Ignore(x => x.IsActive);
            e.Ignore(x => x.EffectivePermissions);
        });
    }

    private void ConfigureCatalog(ModelBuilder b)
    {
        b.Entity<Comic>(e =>
        {
            e.ToTable("comics");
            e.HasKey(x => x.Id);
            e.Property(x => x.OriginalTitle).HasMaxLength(300).IsRequired();
            e.Property(x => x.TranslatedTitle).HasMaxLength(300).IsRequired();
            e.Property(x => x.Slug).HasMaxLength(120).IsRequired();
            e.Property(x => x.Description).HasMaxLength(5000);
            e.Property(x => x.Author).HasMaxLength(200);
            e.Property(x => x.Artist).HasMaxLength(200);
            e.Property(x => x.CoverKey).HasMaxLength(200);
            e.Property(x => x.SearchKey).HasMaxLength(1200).IsRequired();
            e.Property(x => x.Version).IsRowVersion();
            e.HasOne(x => x.TranslationHouse).WithMany().HasForeignKey(x => x.TranslationHouseId).OnDelete(DeleteBehavior.Restrict);
            e.HasMany(x => x.Tags).WithOne().HasForeignKey(x => x.ComicId).OnDelete(DeleteBehavior.Cascade);
            e.Navigation(x => x.Tags).UsePropertyAccessMode(PropertyAccessMode.Field);
            e.HasIndex(x => new { x.TranslationHouseId, x.Slug }).IsUnique().HasFilter("deleted_at IS NULL");
            e.HasIndex(x => new { x.TranslationHouseId, x.UpdatedAt });
            e.HasIndex(x => x.LastChapterPublishedAt);
            e.HasIndex(x => x.SearchKey).HasMethod("gin").HasOperators("gin_trgm_ops");

            e.HasQueryFilter(QueryFilters.Tenant, x => x.TranslationHouseId == CurrentHouseId);
            e.HasQueryFilter(QueryFilters.SoftDelete, x => x.DeletedAt == null);
        });

        b.Entity<Tag>(e =>
        {
            e.ToTable("tags");
            e.HasKey(x => x.Id);
            e.Property(x => x.Name).HasMaxLength(60).IsRequired();
            e.Property(x => x.Slug).HasMaxLength(60).IsRequired();
            e.HasIndex(x => x.Slug).IsUnique();
            e.HasIndex(x => x.Name).IsUnique();
        });

        b.Entity<ComicTag>(e =>
        {
            e.ToTable("comic_tags");
            e.HasKey(x => new { x.ComicId, x.TagId });
            e.HasOne(x => x.Tag).WithMany().HasForeignKey(x => x.TagId).OnDelete(DeleteBehavior.Cascade);
            e.HasIndex(x => x.TagId);
        });

        b.Entity<Chapter>(e =>
        {
            e.ToTable("chapters");
            e.HasKey(x => x.Id);
            e.Property(x => x.ChapterNumber).HasPrecision(8, 2);
            e.Property(x => x.Title).HasMaxLength(200);
            e.Property(x => x.Version).IsRowVersion();
            e.HasOne(x => x.Comic).WithMany().HasForeignKey(x => x.ComicId).OnDelete(DeleteBehavior.Cascade);
            e.HasOne<ChapterPackage>().WithMany().HasForeignKey(x => x.PublishedPackageId).OnDelete(DeleteBehavior.SetNull);
            e.HasIndex(x => new { x.ComicId, x.ChapterNumber }).IsUnique();
            e.HasIndex(x => new { x.ComicId, x.Status });
            e.Ignore(x => x.IsPublished);
            e.Ignore(x => x.CanDelete);

            e.HasQueryFilter(QueryFilters.Tenant, x => x.Comic!.TranslationHouseId == CurrentHouseId);
        });

        b.Entity<ChapterPackage>(e =>
        {
            e.ToTable("chapter_packages");
            e.HasKey(x => x.Id);
            e.Property(x => x.StorageKey).HasMaxLength(200).IsRequired();
            e.Property(x => x.Checksum).HasMaxLength(64);
            e.HasOne(x => x.Chapter).WithMany().HasForeignKey(x => x.ChapterId).OnDelete(DeleteBehavior.Cascade);
            e.HasMany(x => x.Pages).WithOne(x => x.Package).HasForeignKey(x => x.PackageId).OnDelete(DeleteBehavior.Cascade);
            e.Navigation(x => x.Pages).UsePropertyAccessMode(PropertyAccessMode.Field);
            e.HasIndex(x => new { x.ChapterId, x.Version }).IsUnique();
            e.HasIndex(x => x.Status);

            e.HasQueryFilter(QueryFilters.Tenant, x => x.Chapter!.Comic!.TranslationHouseId == CurrentHouseId);
        });

        b.Entity<ChapterPage>(e =>
        {
            e.ToTable("chapter_pages");
            e.HasKey(x => x.Id);
            e.Property(x => x.FileName).HasMaxLength(32).IsRequired();
            e.Property(x => x.SourceName).HasMaxLength(ChapterPage.SourceNameMaxLength);
            e.Property(x => x.StoragePath).HasMaxLength(300).IsRequired();
            e.HasIndex(x => new { x.PackageId, x.PageNumber }).IsUnique();
            e.HasIndex(x => x.ChapterId);

            e.HasQueryFilter(QueryFilters.Tenant, x => x.Package!.Chapter!.Comic!.TranslationHouseId == CurrentHouseId);
        });
    }

    private void ConfigurePublishing(ModelBuilder b)
    {
        b.Entity<ProcessingJob>(e =>
        {
            e.ToTable("processing_jobs");
            e.HasKey(x => x.Id);
            e.Property(x => x.ErrorCode).HasMaxLength(64);
            e.Property(x => x.ErrorMessage).HasMaxLength(1000);
            e.Property(x => x.UploadPath).HasMaxLength(500).IsRequired();
            e.Property(x => x.OriginalFileName).HasMaxLength(255);
            e.OwnsMany(x => x.ExtraPages, o => o.ToJson());
            e.HasOne(x => x.Chapter).WithMany().HasForeignKey(x => x.ChapterId).OnDelete(DeleteBehavior.Cascade);
            e.HasOne<ChapterPackage>().WithMany().HasForeignKey(x => x.PackageId).OnDelete(DeleteBehavior.Cascade);
            e.HasOne<User>().WithMany().HasForeignKey(x => x.RequestedByUserId).OnDelete(DeleteBehavior.Restrict);
            e.HasIndex(x => new { x.Status, x.CreatedAt });
            e.HasIndex(x => x.ChapterId);
            e.Ignore(x => x.IsActive);

            e.HasQueryFilter(QueryFilters.Tenant, x => x.Chapter!.Comic!.TranslationHouseId == CurrentHouseId);
        });

        b.Entity<StorageTask>(e =>
        {
            e.ToTable("storage_tasks");
            e.HasKey(x => x.Id);
            e.Property(x => x.Key).HasMaxLength(300).IsRequired();
            e.Property(x => x.LastError).HasMaxLength(500);
            e.HasIndex(x => x.NextAttemptAt);
        });
    }

    private static void ConfigureMisc(ModelBuilder b)
    {
        b.Entity<AuditLog>(e =>
        {
            e.ToTable("audit_logs");
            e.HasKey(x => x.Id);
            e.Property(x => x.Action).HasMaxLength(100).IsRequired();
            e.Property(x => x.TargetType).HasMaxLength(50);
            e.Property(x => x.TargetId).HasMaxLength(100);
            e.Property(x => x.Ip).HasMaxLength(64);
            e.Property(x => x.Data).HasColumnType("jsonb");
            e.HasIndex(x => x.At);
            e.HasIndex(x => new { x.TranslationHouseId, x.At });
            e.HasIndex(x => new { x.ActorUserId, x.At });
            e.HasIndex(x => x.Action);
        });

        b.Entity<SystemSetting>(e =>
        {
            e.ToTable("system_settings");
            e.HasKey(x => x.Key);
            e.Property(x => x.Key).HasMaxLength(64);
            e.Property(x => x.Value).HasColumnType("jsonb").IsRequired();
        });

        b.Entity<Follow>(e =>
        {
            e.ToTable("follows");
            e.HasKey(x => new { x.UserId, x.ComicId });
            e.HasOne<User>().WithMany().HasForeignKey(x => x.UserId).OnDelete(DeleteBehavior.Cascade);
            e.HasOne<Comic>().WithMany().HasForeignKey(x => x.ComicId).OnDelete(DeleteBehavior.Cascade);
            e.HasIndex(x => x.ComicId);
        });

        b.Entity<ReadingProgress>(e =>
        {
            e.ToTable("reading_progress");
            e.HasKey(x => new { x.UserId, x.ComicId });
            e.HasOne<User>().WithMany().HasForeignKey(x => x.UserId).OnDelete(DeleteBehavior.Cascade);
            e.HasOne<Comic>().WithMany().HasForeignKey(x => x.ComicId).OnDelete(DeleteBehavior.Cascade);
            e.HasOne<Chapter>().WithMany().HasForeignKey(x => x.ChapterId).OnDelete(DeleteBehavior.Cascade);
            e.HasIndex(x => new { x.UserId, x.UpdatedAt });
        });

        b.Entity<ComicViewDaily>(e =>
        {
            e.ToTable("comic_view_daily");
            e.HasKey(x => new { x.ComicId, x.Day });
            e.HasOne<Comic>().WithMany().HasForeignKey(x => x.ComicId).OnDelete(DeleteBehavior.Cascade);
            e.HasIndex(x => x.Day);
        });
    }
}
